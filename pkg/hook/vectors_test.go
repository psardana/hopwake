package hook

import (
	"encoding/json"
	"flag"
	"os"
	"strconv"
	"testing"
	"time"

	"github.com/psardana/hopwake/internal/alias"
	"github.com/psardana/hopwake/internal/journey"
)

// The shared test vectors every hook, in every language, must reproduce.
// They are written by this test with -update and checked by it otherwise,
// so they can only change together with the Go code that defines them.
var update = flag.Bool("update", false, "rewrite testdata/vectors.json")

type seqVector struct {
	Tenant string `json:"tenant"`
	Device string `json:"device"`
	Boot   string `json:"boot"`
	Seq    string `json:"seq"` // decimal: some languages lose precision on large JSON numbers
	ID     string `json:"id"`
}

type timeVector struct {
	Tenant      string `json:"tenant"`
	Device      string `json:"device"`
	Type        string `json:"type"`
	UnixNanos   string `json:"unix_nanos"`   // the reading's own time
	Resolution  string `json:"resolution"`   // finest unit the time uses: s, ms, us or ns
	PrecisionNs string `json:"precision_ns"` // time_precision; "0" keeps the time as given
	Formatted   string `json:"formatted"`    // the time as it enters the ID
	ID          string `json:"id"`
}

type aliasVector struct {
	Kind      string `json:"kind"`
	Value     string `json:"value"`
	Formatted string `json:"formatted"`
}

type vectors struct {
	Note  string        `json:"note"`
	Seq   []seqVector   `json:"seq"`
	Time  []timeVector  `json:"time"`
	Alias []aliasVector `json:"alias"`
}

func buildVectors() vectors {
	v := vectors{Note: "Shared hook test vectors. Generated by `go test ./pkg/hook -run TestVectors -update`; do not edit by hand."}
	seqs := []seqVector{
		{Tenant: "reference", Device: "dev-00042", Seq: "1683"},
		{Tenant: "reference", Device: "dev-00042", Boot: "7", Seq: "12"},
		{Tenant: "reference", Device: "dev-00042", Seq: "0"},
		{Tenant: "reference", Device: "dev-00042", Seq: "18446744073709551615"},
		{Tenant: "conformance", Device: "EMS0000042", Seq: "1"},
		{Tenant: "t", Device: "gerät-ü-✓", Boot: "b", Seq: "9007199254740993"},
		{Tenant: "", Device: "x", Seq: "1"},
	}
	for _, s := range seqs {
		n, _ := strconv.ParseUint(s.Seq, 10, 64)
		s.ID = journey.BootID(s.Tenant, s.Device, s.Boot, n)
		v.Seq = append(v.Seq, s)
	}
	base := time.Date(2026, 11, 18, 10, 0, 0, 0, time.UTC)
	type tc struct {
		dev, typ string
		at       time.Time
		res      string
		prec     time.Duration
	}
	times := []tc{
		{"EMS0000042", "ems.measurements.Measurement", base, "s", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(750 * time.Millisecond), "ms", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(750 * time.Millisecond), "ms", time.Second},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(500 * time.Millisecond), "ms", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(120 * time.Millisecond), "ms", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(123456 * time.Microsecond), "us", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(123456 * time.Microsecond), "us", time.Millisecond},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(123456789), "ns", 0},
		{"EMS0000042", "ems.measurements.Measurement", base.Add(59*time.Second + 999*time.Millisecond), "ms", time.Minute},
		{"EMS0000042", "ems.status.SystemStatus", base, "s", time.Second},
		{"meter-7", "", base.Add(37 * time.Second), "s", 10 * time.Second},
		{"meter-7", "reading", time.Date(1999, 12, 31, 23, 59, 59, 0, time.UTC), "s", time.Second},
	}
	for _, t := range times {
		f := journey.FormatTime(t.at, t.prec)
		v.Time = append(v.Time, timeVector{
			Tenant: "conformance", Device: t.dev, Type: t.typ,
			UnixNanos:   strconv.FormatInt(t.at.UnixNano(), 10),
			Resolution:  t.res,
			PrecisionNs: strconv.FormatInt(int64(t.prec), 10),
			Formatted:   f,
			ID:          journey.TimeID("conformance", t.dev, t.typ, f),
		})
	}
	for _, a := range [][2]string{{"systemId", "100042"}, {"vin", "WVW:ZZZ"}} {
		v.Alias = append(v.Alias, aliasVector{Kind: a[0], Value: a[1], Formatted: alias.Format(a[0], a[1])})
	}
	return v
}

func TestVectors(t *testing.T) {
	got, err := json.MarshalIndent(buildVectors(), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	const path = "testdata/vectors.json"
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	if string(want) != string(got) {
		t.Fatalf("%s is out of date with the journey ID code; run go test ./pkg/hook -run TestVectors -update and check every hook", path)
	}
}
